"""
Central configuration
=====================
Every tunable constant in the live system lives here. Previously they were
scattered as module-level literals across stress_fusion.py,
behavioral_features.py, app.py and stress_detector.py, which made two things
painful: running an ablation meant editing source, and nobody could see the
full set of hand-tuned values in one place.

Provenance is recorded next to each value. Where a number was chosen by
trial and error during PP1, it says so — that honesty is the point, because
PP2 Phase 3 replaces several of these with LEARNED parameters, and we need
to know exactly which ones are currently guesses.

Nothing here changes behaviour. Every value is exactly what the code used
before centralisation; the unit tests (in particular the Default-mode
equivalence test against the archived pre-task-aware implementation) verify
that.
"""

