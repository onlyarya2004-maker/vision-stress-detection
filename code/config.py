# ===========================================================================
# WESAD CALIBRATION ARTIFACT
# ===========================================================================
# calibrated_thresholds.json is generated by wesad_calibration.py and holds
# genuinely useful provenance (LOSO accuracy, per-feature effect sizes).
#
# It ALSO contains 'vision_system_cutoffs' (~0.029 / ~0.683), which the live
# system deliberately does NOT use. Those are percentiles of a logistic
# regression's probability distribution over PHYSIOLOGICAL features — a
# different quantity, on a different scale, from the vision-fused stress
# index. Percentile-matching between two unrelated distributions is not
# principled, and applying them directly would classify almost everything as
# MODERATE (anything above 0.029).
#
# Before centralisation the loader read this file and then silently discarded
# those cutoffs while printing "threshold source: ... WESAD JSON loaded",
# which overstated what was happening. It is now explicit.
#
# PP2 Phase 3 replaces the hand-tuned cutoffs above with thresholds LEARNED
# from labelled data, which is the principled fix.
